import "./env";
import { expect, test } from "@playwright/test";
import { resolve } from "node:path";
import { mkdir } from "node:fs/promises";

test("resource workspace expands, restores, closes and keeps selected overflow tabs visible", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await mkdir(".tmp/side-design", { recursive: true });
  await page.setViewportSize({ width: 1200, height: 900 });
  const fixture = `/@fs/${resolve("e2e/fixtures/local-side-workspace.tsx")}`;
  await page.route("**/__test/side-workspace", (route) => route.fulfill({ contentType: "text/html", body: `<div id="root"></div><script type="module">import RefreshRuntime from '/@react-refresh'; RefreshRuntime.injectIntoGlobalHook(window); window.$RefreshReg$=()=>{}; window.$RefreshSig$=()=>type=>type; window.__vite_plugin_react_preamble_installed__=true; await import(${JSON.stringify(fixture)});</script>` }));
  await page.goto("/__test/side-workspace");
  const main = page.getByRole("textbox", { name: "Main draft" });
  await expect(main).toBeVisible();
  await main.fill("Keep main input");
  expect((await main.boundingBox())!.width).toBeGreaterThan(1150);
  await page.getByRole("button", { name: "Open file 1", exact: true }).click();
  await expect(page.getByText("preview text", { exact: true })).toBeVisible();
  expect((await main.boundingBox())!.width).toBeLessThan(900);
  const beforeResize = (await main.boundingBox())!.width;
  await page.getByRole("separator", { name: "Resize right workspace", exact: true }).press("ArrowRight");
  expect(errors).toEqual([]);
  await expect.poll(async () => (await main.boundingBox())!.width).toBeGreaterThan(beforeResize);
  for (let index = 2; index <= 5; index++) await page.getByRole("button", { name: `Open file ${index}`, exact: true }).click();
  const selected = page.getByRole("tab", { selected: true });
  await expect(selected).toHaveText("long-preview-file-5.ts");
  const strip = (await page.getByRole("tablist").boundingBox())!;
  await expect.poll(async () => { const tab = (await selected.boundingBox())!; return tab.x >= strip.x - 1 && tab.x + tab.width <= strip.x + strip.width + 1; }).toBe(true);
  await page.screenshot({ path: ".tmp/side-design/12-rendered-workspace-wide.png" });
  await page.getByRole("button", { name: "Expand right workspace", exact: true }).click();
  await expect(main).toBeHidden();
  await expect(page.getByRole("button", { name: "Return to main chat", exact: true })).toBeVisible();
  await page.screenshot({ path: ".tmp/side-design/13-rendered-workspace-expanded.png" });
  await page.getByRole("button", { name: "Restore split view", exact: true }).click();
  await expect(main).toBeVisible();
  await expect(main).toHaveValue("Keep main input");
  await page.getByRole("button", { name: "Close right workspace", exact: true }).click();
  await expect.poll(async () => (await main.boundingBox())!.width).toBeGreaterThan(1150);
  await page.getByRole("button", { name: "Toggle workspace", exact: true }).click();
  await page.setViewportSize({ width: 620, height: 800 });
  await expect(main).toBeHidden();
  await page.screenshot({ path: ".tmp/side-design/14-rendered-workspace-narrow.png" });
  await page.getByRole("button", { name: "Return to main chat", exact: true }).click();
  await expect(main).toBeVisible();
  await expect(main).toHaveValue("Keep main input");
  await page.getByRole("button", { name: "Open HTML report", exact: true }).click();
  await expect(page.getByRole("tab", { name: "cases.html", exact: true })).toBeVisible();
  const report = page.frameLocator('iframe[title="cases.html"]');
  await expect(report.getByRole("heading", { name: "Case review", exact: true })).toBeVisible();
  await expect(report.getByText("Local report preview", { exact: true })).toBeVisible();
  await expect(page.locator("body")).not.toHaveAttribute("data-error");
  expect(errors).toEqual([]);
});
